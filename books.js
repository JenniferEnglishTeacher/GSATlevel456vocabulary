window.vocabZoneOfKey = function (key) {
  const m = /^([a-z0-9]+)-(\d+):(\d+)$/i.exec(String(key || ""));
  if (!m) return null;
  const id = Object.keys(window.VOCAB_ZONES).find(z => window.VOCAB_ZONES[z].prefix === m[1]);
  return id ? { zone: id, unit: Number(m[2]), index: Number(m[3]) } : null;
};
